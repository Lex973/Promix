TAIL_MATERIAL = ('Расход, состав, время высыхания и другие характеристики — только по паспорту '
                 'производителя: спросите у технолога PROMIX, подскажем и подберём под задачу. '
                 'Наличие и срок поставки подтвердим при заказе.')

TAIL_TOOL = ('Точные размеры и комплектация — по данным производителя. Если сомневаетесь, '
             'что подойдёт под вашу задачу, спросите у технолога PROMIX. '
             'Наличие и срок поставки подтвердим при заказе.')


def detect_type(name: str):
    for pattern, short, purpose in TYPES:
        if re.search(pattern, name, re.IGNORECASE):
            return short, purpose
    return None, None


def build(row):
    name, brand, cat, sku = row['Наименование'], row['Бренд'], row['Категория'], row['Артикул']
    short, purpose = detect_type(name)

    # Короткое описание — одна строка, идёт и в мета-описание страницы.
    if short:
        head = f'{short} {brand}'.strip() if brand and brand.lower() not in short.lower() else short
        short_desc = f'{head}. Раздел «{cat}», артикул {sku}.'
    else:
        short_desc = f'{name}. Раздел «{cat}», артикул {sku}.'

    # Название не повторяем: оно и так стоит заголовком над описанием.
    paragraphs = []
    if purpose:
        paragraphs.append(purpose)
    else:
        paragraphs.append(f'Раздел каталога — {CATEGORIES.get(cat, cat.lower())}. Назначение и размеры — в названии позиции.')

    line2 = BRANDS.get(brand) or (f'Бренд {brand}.' if brand else '')
    line2 = (line2 + ' ' if line2 else '') + f'Артикул {sku}.'
    paragraphs.append(line2)
    paragraphs.append(TAIL_MATERIAL if short in MATERIALS else TAIL_TOOL)

    return short_desc, '\n\n'.join(paragraphs)


def main():
    rows = list(csv.DictReader(io.open('katalog-dlya-sayta.csv', encoding='utf-8-sig'), delimiter=';'))
    typed = 0

    with io.open('woo-descriptions.csv', 'w', encoding='utf-8', newline='') as out:
        w = csv.writer(out)
        w.writerow(['SKU', 'Short description', 'Description'])
        for r in rows:
            short_desc, desc = build(r)
            typed += 1 if detect_type(r['Наименование'])[0] else 0
            w.writerow([r['Артикул'], short_desc, desc])

    print(f'{len(rows)} rows, type detected for {typed}')


if __name__ == '__main__':
    main()
