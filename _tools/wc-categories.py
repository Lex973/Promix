def classify(row):
    pid = int(row['ID'])
    if pid in OVERRIDES:
        return OVERRIDES[pid]
    name = row['Наименование'].lower()
    for pattern, sub in RULES:
        if re.search(pattern, name):
            return sub
    return ''


