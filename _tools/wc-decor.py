def main():
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / 'decor.csv'

    with io.open(path, 'w', encoding='utf-8', newline='') as f:
        w = csv.writer(f, delimiter=';')
        w.writerow(['SKU', 'Name', 'Price', 'Unit', 'Category', 'Brand', 'Image', 'Short', 'Description'])
        for sku, name, price, image, short, paragraphs in PRODUCTS:
            if not (OUT / 'img' / image).is_file():
                raise SystemExit(f'Нет картинки {image} для {sku}')
            w.writerow([sku, name, price, UNIT, CATEGORY, BRAND, image, short, '\n\n'.join(paragraphs + [TAIL])])

    print(f'{len(PRODUCTS)} rows -> {path}')


if __name__ == '__main__':
    main()
